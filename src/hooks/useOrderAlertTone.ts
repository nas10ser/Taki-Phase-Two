/**
 * useOrderAlertTone — إنذارٌ لا يسكت حتى يُجاب الطلب (v16.58)
 * ═══════════════════════════════════════════════════════════════════════════
 * أمرُ ناصر: «عند إرسال طلبٍ من متجر أريد نفس نغمة الإشعار، ولكن تتكرّر إلى أن
 * يُستلم الطلب من التاجر أو يُلغى من أحد الطرفين — لأن التاجر قد لا ينتبه من
 * نغمةٍ وحدة». وبعد تجربة v16.57: «**بدون توقّف** — ونغمةٌ واحدةٌ لن يفرّق بها
 * التاجرُ بينها وبين إشعار، خصوصاً مع عشرات الطلبات في نفس الوقت».
 *
 * 🪤 **والإسكاتُ بمقارنة القائمة لا بحدثٍ بعينه.** ربطُه بـ«حدثِ استلام» يترك
 *    الإنذارَ يرنّ إن وصل التغييرُ بمسارٍ آخر: إعادةُ جلبٍ · حدثُ ريل‑تايم
 *    مختلف · إلغاءٌ من المشتري · انتهاءُ المهلة. أمّا مقارنةُ القائمة فتُصيب
 *    كلَّ المسارات — ما خرج منها يسكت، وما دخلها يُبدئ الرنين.
 *
 * 🪤 **وإنذارٌ واحدٌ لا إنذارٌ لكلّ طلب**: الخدمةُ تأخذ القائمةَ كلَّها فترنّ
 *    ما دام فيها شيء. (عشرُ مؤقّتاتٍ متراكبةٍ كانت تشويشاً لا تنبيهاً.)
 *
 * 🪤 وللتاجر وحده: المشتري يعرف أنه حجز للتوّ، فالإنذارُ عليه إزعاج.
 *
 * 🪤 وأُخرج من `AppContext` لأن السقّافة رفضت نموَّها — **وهي التصميم**:
 *    هذه وحدةٌ قائمةٌ بذاتها لا سطرٌ في سياقٍ من أربعة آلاف سطر.
 */
import { useEffect } from 'react';
import { syncOrderAlarm, stopOrderAlarm, unlockSound } from '../services/notificationSound';

export const useOrderAlertTone = (bookings: any[] | undefined, userId: string | undefined): void => {
    /**
     * 🔴 فتحُ قفل الصوت عند أوّل لمسة — وهنا لأن هذا الخطّاف يعمل في كلّ
     *    جلسة. بلا ذلك تُحجب **كلُّ** نغمةٍ في التطبيق بسياسة التشغيل
     *    التلقائي، وهو سببُ «الصوتُ في الكود ولا يُسمع» الذي بلّغ عنه ناصر.
     */
    useEffect(() => { unlockSound(); }, []);

    useEffect(() => {
        if (!userId) { stopOrderAlarm(); return; }
        const waiting = (bookings || [])
            .filter((b: any) => b?.status === 'pending' && b?.deal?.storeId === userId)
            .map((b: any) => `order:${b.barcode}`)
            .filter(Boolean);
        syncOrderAlarm(waiting);
    }, [bookings, userId]);

    useEffect(() => () => { stopOrderAlarm(); }, []);
};

export default useOrderAlertTone;
