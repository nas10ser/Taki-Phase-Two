/**
 * memoAsync — نداءٌ واحدٌ لنفس السؤال، ولو سأله خمسةُ مكوّنات (v16.17)
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔴 **ما قِيس على الإنتاج** (١٣ نوفمبر ٢٠٢٦، تنقّلٌ داخل التطبيق):
 *   · `/deal/<id>`  ⇒ `store_policies` **مرّتان** في فتحةٍ واحدة.
 *   · `/store/<id>` ⇒ **أحدَ عشرَ نداءً**، منها أربعةُ أسئلةٍ صغيرةٍ عن
 *     **نفس المتجر** (السياسة · التوثيق · عددُ المتابعين · سقفُ الباقة).
 *   وكلُّها إجاباتٌ لا تتغيّر أثناء تصفّحٍ واحد.
 *
 * ⇒ طبقتان، وكلتاهما ضروريّة:
 *   ① **مشاركةُ الطلب الطائر**: السائلُ الثاني يستلم **نفسَ الوعد** ما دام
 *      الأوّل لم يُحسم ⇒ لا يُهمَل سؤالٌ ولا يتأخّر جواب، يسقط الطلبُ الزائد
 *      وحده. (نفسُ ما حلّ نداءَي الواجهة المتطابقين في v16.15.)
 *   ② **ذاكرةٌ قصيرةٌ بعمرٍ صريح**: فالتنقّلُ من عرضٍ إلى صفحة متجره لا
 *      يُعيد سؤالَ الخادم عمّا سأله قبل ثانيتين.
 *
 * 🪤 ولا ذاكرةَ بلا عمر: جوابٌ يبقى أبداً أسوأ من نداءٍ مكرَّر — فالتاجرُ
 *    يعدّل سياستَه فلا تظهر. والعمرُ يُمرَّر صريحاً عند كلّ استعمال.
 * 🪤 و**الفشلُ لا يُخزَّن**: خطأُ شبكةٍ عابر كان سيُجمَّد دقيقةً كاملة.
 * 🪤 والمفتاحُ يشمل كلَّ ما يُغيّر الجواب (المعرّف وأيُّ وسيط) — ومفتاحٌ
 *    ناقصٌ يُسلّم جوابَ متجرٍ لمتجرٍ آخر، وهو أخطر من كلّ ما سبق.
 */
interface Entry<T> { at: number; value: T }

const live = new Map<string, Promise<any>>();
const done = new Map<string, Entry<any>>();

/** يُفرَّغ عند الخروج/الدخول: الجوابُ قد يعتمد على هويّة السائل. */
export const clearAsyncMemo = (): void => { live.clear(); done.clear(); };

export const memoAsync = <T>(key: string, ttlMs: number, run: () => Promise<T>): Promise<T> => {
    const hit = done.get(key);
    if (hit && Date.now() - hit.at < ttlMs) return Promise.resolve(hit.value as T);
    const flying = live.get(key);
    if (flying) return flying as Promise<T>;
    const p = run()
        .then((v) => { done.set(key, { at: Date.now(), value: v }); return v; })
        .finally(() => { live.delete(key); });
    live.set(key, p);
    return p;
};

export default memoAsync;
