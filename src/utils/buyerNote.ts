/**
 * buyerNote — ملاحظةُ المشتري من عمود `notes` (v16.23)
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔴 **بلاغُ ناصر (١٣ نوفمبر ٢٠٢٦)**: «في الفاتورة لا بدّ أن يضع ملاحظات
 *    المشتري … حتى يلتزموا بها ولا يكون هناك أي خطأ عند إنشاء الطلب».
 *
 * والقياسُ على جدة: **٦١ طلباً من ١٢٤ تحمل ملاحظة، و٦٠ منها لم تُطبع قطّ.**
 * السببُ أن الفاتورةَ كانت تستخرجها بنمطٍ يشترط بادئة `📝`:
 *     /📝\s*([\s\S]*?)(?:\n💰|$)/
 * وتلك صيغةٌ **لم يعد يكتبها أحد** — صفٌّ واحدٌ من ١٢٤ يحملها. فالمُستخرِجُ
 * كان يقرأ تنسيقاً ميّتاً، ويعيد `undefined` دائماً، والقالبُ يطبع فراغاً.
 * 🪤 وهو عيبٌ **صامتٌ تماماً**: الملاحظةُ تظهر في «حجوزاتي» (تقرأ `notes`
 *    مباشرةً) فيظنّ الجميعُ أنها وصلت — وهي غائبةٌ عن الورقة التي بيد التاجر.
 *
 * ── الصيغُ الثلاثُ كما هي في البيانات (قِيست، لا افتُرضت) ─────────────────
 *   (أ) مركَّبةٌ قديمةٌ بملاحظة:
 *       `📦 تفاصيل الطلب:⏎• …⏎⏎📝 سوف ناتي خلال ساعه⏎💰 الإجمالي: 80 ر.س`
 *       ⇒ الملاحظةُ ما بين `📝` وسطر `💰`.
 *   (ب) مركَّبةٌ قديمةٌ **بلا** ملاحظة:
 *       `📦 تفاصيل الطلب:⏎• علم صغير ×1 (20 ر.س)⏎💰 الإجمالي: 20 ر.س`
 *       ⇒ **لا ملاحظةَ أصلاً**. وهذا هو الفرعُ الذي لا يُنسى: بلا تمييزِه
 *         تُطبع تفاصيلُ الطلب نفسُها على أنها «ملاحظة المشتري».
 *   (ج) نصٌّ خامٌّ (ما يكتبه التطبيقُ اليوم): `اريد الحليب حرارتها وسط`
 *       ⇒ النصُّ كلُّه.
 *
 * 🔴 والقاعدةُ **مكتوبةٌ هنا وفي `bot_get_booking_invoice` على جدة**، لأن
 *    فاتورةَ البوت تُبنى في القاعدة. وتُقاس الاثنتان على نفس الصيغ الثلاث.
 */

/** علاماتُ النصّ الذي يكتبه النظامُ لا المشتري. */
const MACHINE = /[📦📏💰]/u;

export const buyerNoteFromNotes = (notes?: string | null): string | undefined => {
    const raw = String(notes ?? '');
    if (!raw.trim()) return undefined;

    // (أ) الصيغةُ المركَّبةُ القديمة: ما بين `📝` وأوّلِ سطرٍ يبدأ بـ`💰`.
    const marked = /📝[ \t]*([\s\S]*?)(?:\n[ \t]*💰|$)/.exec(raw);
    if (marked) {
        const v = marked[1].trim();
        return v || undefined;
    }

    // (ب) مركَّبةٌ بلا ملاحظة ⇒ لا شيء. وتمييزُها بعلامات النظام وحدها:
    //     المشتري لا يكتب `📦` ولا `💰 الإجمالي`.
    if (MACHINE.test(raw)) return undefined;

    // (ج) نصٌّ خامٌّ كتبه المشتري.
    return raw.trim() || undefined;
};

export default buyerNoteFromNotes;
