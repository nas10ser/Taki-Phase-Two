/**
 * arPlural — جمعُ العدد بالعربية في مكانٍ واحد (v14.93)
 * ═══════════════════════════════════════════════════════════════════════════
 * 🪤 الدرس المدفوع مرّتين: «٦ ساعة» (v14.92) و«٣ رسالة» (هنا). العربية ليست
 *    `${n} ${unit}`: للواحد صيغة، وللاثنين مثنّى، ولثلاثةٍ إلى عشرة جمعُ قلّة،
 *    ولما فوقها مفردٌ منصوب. وكل موضعٍ يكتبها يدوياً يُخطئ في واحدةٍ منها.
 *
 * وكان في المشروع محرّكٌ لهذا داخل `bookingHold.ts` **للساعات وحدها**. فلمّا
 * احتاجت الرسائلُ مثلَه، كان البديل نسخَه — ونسخةٌ ثانية تنحرف. فخرج المحرّك
 * إلى هنا، و`bookingHold.ts` صار من زبائنه لا نسخةً موازية له.
 *
 * 🪤 وتُطابق هذه الصيغُ دالّةَ القاعدة `taki_ar_messages()` عمداً: رسالةُ الخطأ
 *    قد تأتي من الخادم (P0004) أو تُصاغ هنا، فاختلافُهما يُري المستخدم نصّين
 *    مختلفين للحالة نفسها.
 */

export interface ArForms {
    /** ١ — «ساعة واحدة» / «رسالة واحدة» */
    one: string;
    /** ٢ — المثنّى المرفوع: «ساعتان» / «رسالتان» */
    two: string;
    /** ٢ بعد حرف جرّ — المثنّى المنصوب/المجرور: «ساعتين». اتركه لغير المحتاج. */
    twoGen?: string;
    /** ٣‑١٠ — جمع القلّة: «ساعات» / «رسائل» (بلا العدد؛ يُضاف تلقائياً) */
    few: string;
    /** ١١ فما فوق — مفردٌ: «ساعة» / «رسالة» (بلا العدد؛ يُضاف تلقائياً) */
    many: string;
}

/**
 * صياغةُ الرقم نفسه. الافتراضُ `String` — أي الشكلُ الذي كانت عليه الدالّة
 * قبل v15.81 بالحرف، فلا يتغيّر مخرجٌ قائمٌ واحد بإضافة المُعامل.
 */
export type ArNumFmt = (x: number) => string;

/**
 * يُرجع العدد مصوغاً. `genitive` للمواضع بعد حرف جرّ («خلال ساعتين»).
 * 🪤 الكسور تُعامَل معاملة ما فوق العشرة («١٫٥ ساعة») — وهي واردة فعلاً:
 *    ومهلة الحجز تقبل الكسور فوق الأرضيّة (١٫٥ · ٢٫٥).
 *
 * 🪤 و`fmt` أُضيف لسببٍ قِيس، لا للتوسيع: لوحةُ الإدارة توحّد شكلَ الرقم على
 *    `admNum` (فواصلُ الآلاف وأرقامٌ لاتينية). فلو استُبدلت عباراتُها المصنوعة
 *    بيدها بـ`arCount` بلا هذا المُعامل، لسقطت فاصلةُ الآلاف فوق ٩٩٩ بصمت —
 *    وهو **سببُ** كتابةِ تلك العبارات بالأيدي أصلاً. فالمُعاملُ يُسبق التحويلَ،
 *    وإلّا صار الإصلاحُ يُنتج عيباً ثانياً أهدأ من الأوّل.
 * 🪤 ولا يُمسّ الرقمُ في فرعَي ١ و٢: الصيغتان لا تحويان رقماً إطلاقاً
 *    («يوم واحد» · «يومان»)، فتمريرُ `fmt` هناك لا معنى له.
 */
export const arCount = (
    n: number, f: ArForms, genitive = false, fmt: ArNumFmt = String,
): string => {
    if (!Number.isFinite(n)) return `${fmt(n)} ${f.many}`;
    if (!Number.isInteger(n)) return `${fmt(n)} ${f.many}`;
    if (n === 1) return f.one;
    if (n === 2) return genitive ? (f.twoGen || f.two) : f.two;
    if (n >= 3 && n <= 10) return `${fmt(n)} ${f.few}`;
    return `${fmt(n)} ${f.many}`;
};

export const HOURS: ArForms = {
    one: 'ساعة واحدة', two: 'ساعتان', twoGen: 'ساعتين', few: 'ساعات', many: 'ساعة',
};

export const MINUTES: ArForms = {
    one: 'دقيقة واحدة', two: 'دقيقتان', twoGen: 'دقيقتين', few: 'دقائق', many: 'دقيقة',
};

export const MESSAGES: ArForms = {
    one: 'رسالة واحدة', two: 'رسالتان', twoGen: 'رسالتين', few: 'رسائل', many: 'رسالة',
};

/** «٣ رسائل» / «رسالة واحدة» — يطابق `taki_ar_messages()` في القاعدة. */
export const arMessages = (n: number): string => arCount(n, MESSAGES);

/** الإنجليزية أبسط، لكنها تُخطئ أيضاً: «1 hours». */
export const enCount = (n: number, one: string, many: string): string =>
    n === 1 ? `one ${one}` : n === 2 ? `two ${many}` : `${n} ${many}`;
