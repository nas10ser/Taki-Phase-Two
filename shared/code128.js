const START_B = 104;
const STOP = 106;

/**
 * يحوّل النص إلى سلسلة عروض العناصر (قضبان/فراغات) لباركود Code 128B.
 * يُرجع `null` لما لا يحمل محرفاً مقروءاً واحداً.
 *
 * 🪤 لا باركود خير من باركودٍ يُمسح إلى فراغ: رمز كاشير من مسافات (أو عربيٌّ
 *    كامل يُنظَّف إلى لا شيء) كان يُنتج ورقةً تُطبع وتوهم التاجر أنها تعمل.
 * 🪤 و`String(null)` = "null" — فمن لا يحرس الفراغ يطبع باركوداً يقرؤه
 *    الكاشير حرفياً «null».
 */
function encode128B(text) {
  // Code 128B يقبل ASCII المطبوع 32..126 فقط — ننظّف ما عداه.
  const clean = String(text == null ? '' : text).replace(/[^\x20-\x7E]/g, '');
  if (!clean.trim()) return null;

  const values = [START_B];
  for (let i = 0; i < clean.length; i++) {
    values.push(clean.charCodeAt(i) - 32);   // ' ' (32) → 0 … '~' (126) → 94
  }
  // مجموع التحقّق الموزون: البداية + Σ(القيمة × موضعها 1..n) mod 103
  let sum = START_B;
  for (let i = 1; i < values.length; i++) sum += values[i] * i;
  values.push(sum % 103);
  values.push(STOP);

  let modules = '';
  for (const v of values) modules += PATTERNS[v];
  return modules;
}

/** عدد وحدات النمط (مجموع أرقامه) — يلزم لحساب عرض الباركود قبل الرسم. */
const modulesCount = (m) => [...m].reduce((s, d) => s + parseInt(d, 10), 0);

module.exports = { encode128B, modulesCount, PATTERNS, START_B, STOP };
