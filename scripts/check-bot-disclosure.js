#!/usr/bin/env node
/**
 * check-bot-disclosure.js — إفصاحُ قناتَي المراسلة (v16.56)
 *
 * ── العيبُ الذي يحرسه ───────────────────────────────────────────────────
 * 🔴 **نصٌّ وقفلٌ يفترقان.** في v15.80 أُسقط إفصاحُ تيليجرام وواتساب من سياسة
 *    الخصوصية بقرار المالك، ووُضع مشغّلٌ في القاعدة يرفض تشغيلَ القناة حتى
 *    يُعاد (`BOT_CHANNEL_NOT_DISCLOSED`). وفي v16.56 أُعيد الإفصاحُ ليُشغَّل
 *    البوتان. والخطرُ في الاتجاهين:
 *      · إفصاحٌ يختفي من موضعٍ واحدٍ ويبقى في الباقي ⇒ وثيقةٌ ناقصة.
 *      · أو يختفي كلُّه والقناةُ تعمل ⇒ معالجةُ بياناتٍ بلا إفصاح.
 *
 * 🪤 والحارسُ **نصّيٌّ بالضرورة**: Vercel تبني بلا شبكةٍ إلى القاعدة، فلا
 *    يستطيع قراءةَ `bot_channels_disclosed`. فما يضمنه هو **اتّساقُ النصّ
 *    مع نفسه**: المواضعُ الأربعةُ معاً أو لا شيء.
 *
 * 🪤 ويُجرَّد التعليقُ قبل أيّ فحص: هذا الملفُّ يذكر نفسَ الكلمات.
 */
const fs = require('fs');
const path = require('path');

const R = (p) => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
const strip = (src) => src
    .replace(/(^[ \t]*|\{)\/\*[\s\S]*?\*\//gm, '$1')
    .replace(/^[ \t]*\/\/[^\n]*$/gm, '')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
    .replace(/<!--[\s\S]*?-->/g, '');

let pass = 0, fail = 0;
const check = (name, ok, detail) => {
    console.log(`${ok ? '  ✓' : '  ✗'} ${name}`);
    if (!ok && detail) console.log(`      ${detail}`);
    ok ? pass++ : fail++;
};

const PRIV = strip(R('src/pages/legal/Privacy.tsx'));

console.log('\nإفصاحُ قناتَي المراسلة — النصُّ والقفلُ لا يفترقان');

/**
 * المواضعُ الأربعةُ التي أُسقطت في v15.80 وأُعيدت في v16.56 — كلُّ موضعٍ
 * بعربيّته وإنجليزيّته. ومرساةُ كلٍّ **جملةٌ من داخله** لا كلمةٌ عامّة:
 * «تيليجرام» وحدها تظهر في شاشاتٍ أخرى كثيرة فلا تصلح دليلاً.
 */
const SPOTS = [
    { ar: 'عبر بوت تاكي على تيليجرام وواتساب',       en: 'the TAKI bot on Telegram and WhatsApp',   what: 'نطاقُ السياسة' },
    { ar: 'بيانات قنوات المراسلة',                    en: 'Messaging-channel data',                   what: 'ما نجمعه' },
    { ar: 'عبر قنوات المراسلة',                       en: 'Through messaging channels',               what: 'مصادرُ الجمع' },
    { ar: 'قناتا المراسلة',                            en: null,                                       what: 'النقلُ خارج المملكة' },
];

for (const s of SPOTS) {
    check(`الإفصاحُ في «${s.what}» — عربيّ`, PRIV.includes(s.ar),
        `سقط من سياسة الخصوصية. إمّا يُعاد، وإمّا تُطفأ القناةُ ويُضبط `
        + `bot_channels_disclosed = false — ولا يصحّ نصٌّ ناقصٌ وقناةٌ تعمل.`);
    if (s.en) {
        check(`والإنجليزيّ`, PRIV.includes(s.en),
            'النسخةُ الإنجليزيّة ناقصةٌ — والوثيقتان تُقرآن على أنهما نصٌّ واحد.');
    }
}

// ── ووصفُ التجّار في `index.html` يذكر القناة أيضاً ──────────────────────
check('وصفُ التجّار في `index.html` يذكر بوت تيليجرام',
    /عبر لوحة تحكم أو عبر بوت تيليجرام/.test(strip(R('index.html'))),
    'نصٌّ عامٌّ تقرؤه محرّكاتُ البحث — ووصفُ قناةٍ لا نُقدّمها (أو إغفالُ قناةٍ '
    + 'نُقدّمها) كلاهما خطأ.');

// ── والوعدُ يُتتبَّع إلى الكود الذي ينفّذه (درس v14.82) ───────────────────
check('ووعدُ «تسجيل الخروج» منفَّذٌ في تيليجرام',
    /logout/.test(R('server/bot.js')),
    'الوثيقةُ تَعِد بأمرٍ لا وجودَ له');
check('وفي واتساب',
    /تسجيل الخروج|logout/.test(R('server/flows/whatsapp.js')),
    'الوثيقةُ تَعِد بخيارٍ لا وجودَ له في قائمة واتساب');
check('ووعدُ «رمزٌ مؤقّت تُصدره من التطبيق» منفَّذ',
    /bot_create_link_token/.test(R('src/components/TelegramLinkButton.tsx')),
    'الوثيقةُ تَعِد بمسارِ ربطٍ لا وجودَ له');

// ── ورمزُ الحارس يُترجَم للمستخدم ولا يظهر خاماً ────────────────────────
{
    const w = strip(R('src/services/platformSettingWrite.ts'));
    check('رمزُ `BOT_CHANNEL_NOT_DISCLOSED` مترجَمٌ في مسار كتابة الإعدادات',
        /BOT_CHANNEL_NOT_DISCLOSED/.test(w) && /سياسةُ الخصوصية لا تذكر/.test(w),
        'بلاغُ ناصر ٢٤ نوفمبر: ظهر الرمزُ إنجليزياً خاماً بلا سببٍ ولا خطوةٍ تالية');
    check('ويُطابَق بالاحتواء لا بالمساواة',
        /raw\.includes\(g\.code\)/.test(w),
        'رسالةُ PostgREST تلفّ الرمزَ بنصٍّ آخر، فالمساواةُ تُسقط المطابقة');
    check('ويُفحص `hint` و`details` أيضاً',
        /\.hint/.test(w) && /\.details/.test(w),
        'الحارسُ يضع الرمزَ في HINT، وبعضُ الرموز لا تعبر إلّا فيه (درس v15.74)');
}

console.log(`\n${fail === 0 ? '✅' : '❌'} ${pass} ناجح · ${fail} فاشل\n`);
process.exit(fail === 0 ? 0 : 1);
