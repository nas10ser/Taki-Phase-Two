#!/usr/bin/env node
/**
 * حقلُ مدّة البانر — **مرئيٌّ لا موجودٌ فحسب**.
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔴 العيبُ الذي وُلد له هذا الحارس، وقد وقع فعلاً (بلاغُ ناصر ٢٠ نوفمبر،
 *    بعد أن أعلنتُ الميزةَ منشورة): «لا زال البنر لا يوجد به تاريخ؟»
 *
 *    وقِيس حينها أن **كلَّ طبقةٍ كانت سليمة**:
 *      · العمود `banners.starts_at` موجودٌ على الإنتاج ✅
 *      · والنصّ «مدّةُ ظهور البانر» داخل الحزمة المنشورة ✅
 *    ومع ذلك لم يره ناصر — لأن الإدراج وقع **داخل `<details>` مطويّة**
 *    عنوانُها «أو رابط خارجي بدل المتجر (متقدّم)». فالحقلُ موجودٌ ومشحونٌ
 *    ومخفيٌّ خلف قسمٍ لا علاقةَ له به.
 *
 * 🔴 **والدرس**: وجودُ النصّ في الحزمة لا يُثبت أنه **يُرى**. والمرساةُ
 *    الموضعيّة (`rindex('<div')`) التقطت أقربَ `<div` وهو داخل الطيّ —
 *    وامتحانُ الأنواع أخضرُ، والبحثُ النصّيُّ يجده. فيُقرأ **موضعُ التصيير**.
 *
 * 🪤 ويُجرَّد التعليقُ قبل أيّ عدّ: أوّلُ نسخةٍ من هذا الفحص عدّت كلمة
 *    `<details>` **داخل تعليقي أنا** فأعلنت الحقلَ مطويّاً وهو ظاهر.
 *    (وهو الفخُّ المسجَّل: «الحارسُ قد يقرأ تعليقَه هو».)
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const FILE = 'src/components/admin/BannerModal.tsx';

let pass = 0, fail = 0;
const check = (name, ok, detail) => {
    console.log(`${ok ? '  ✓' : '  ✗'} ${name}`);
    if (!ok && detail) console.log('      ' + detail);
    ok ? pass++ : fail++;
};

console.log('\nحقلُ مدّة البانر — مرئيٌّ لا موجودٌ فحسب');

const raw = fs.readFileSync(path.join(root, FILE), 'utf8');
// تجريدُ تعليقات JSX و JS قبل أيّ فحصٍ بنيويّ
const src = raw
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
    .replace(/(^[ \t]*|\{)\/\*[\s\S]*?\*\//gm, '$1')
    .replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const at = src.indexOf('<BannerSchedule');
check('الحقلُ مُصيَّرٌ في نافذة البانر', at !== -1,
    'لا تصييرَ له إطلاقاً — الميزةُ ميّتة');

if (at !== -1) {
    const before = src.slice(0, at);

    // ① خارج أيّ `<details>` مطويّة — هذا هو البلاغُ بعينه.
    const openDetails = (before.match(/<details/g) || []).length
        - (before.match(/<\/details>/g) || []).length;
    check('خارج أيّ قسمٍ مطويّ `<details>`', openDetails === 0,
        `داخل ${openDetails} قسمٍ مطويّ — سيُشحن ولا يراه أحد`);

    // ② وليس خلف شرطِ تصيير: حقلٌ يظهر أحياناً ليس حقلاً.
    const tail = before.slice(-400);
    check('وليس خلف شرطِ تصييرٍ مباشر', !/\{\s*[A-Za-z_$][\w$.?]*\s*&&\s*\(?\s*$/.test(tail),
        'مربوطٌ بشرطٍ — قد لا يظهر');

    // ③ وقبل «مكان الظهور»: الترتيبُ الذي طلبه ناصر (المدّة ثمّ الموضع).
    const posAt = src.indexOf('مكان الظهور');
    check('ويسبق «مكان الظهور»', posAt !== -1 && at < posAt);
}

// ④ ويُحفظ فعلاً: حقلٌ يُملأ ولا يُرسَل أسوأُ من غيابه.
check('القيمتان تدخلان حمولةَ الحفظ',
    /starts_at:\s*sched\.starts_at/.test(src) && /expires_at:\s*sched\.expires_at/.test(src),
    'لا تُكتبان في الصفّ — سيُملأ الحقلُ ولا يُحفظ شيء');

// ⑤ والمحرّرُ يُفتح على ما هو محفوظ.
check('ويُبذَر من الصفّ عند التعديل', /initial=\{initial\}/.test(src));

console.log(`\n${fail ? '❌' : '✅'} حقلُ مدّة البانر: ${pass} ناجحاً · ${fail} فاشلاً`);
process.exit(fail ? 1 : 0);
