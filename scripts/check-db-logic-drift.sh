#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
# TAKI · حارسُ انحراف عقل القاعدة — هل لقطةُ المستودع هي الحيّةُ نفسُها؟
#
#   bash scripts/check-db-logic-drift.sh            # تقريرٌ، وخروجٌ ١ عند انحراف
#   bash scripts/check-db-logic-drift.sh --names    # أسماءُ المنحرفة فقط
#
# 🪤 السؤالُ الذي كان يُسأل خطأً: «هل الدالّةُ موجودةٌ في المستودع؟» — وقِيس
#   ٨ نوفمبر ٢٠٢٦ فكان جوابُه مطمئناً كذباً. من ٦٤٢ دالّةٍ حيّة، ستّةَ عشرَ
#   وحدها غائبةٌ عن المستودع **وكلُّها من إضافة `pg_trgm`** لا من تاكي. أي أنّ
#   «١٨٩ دالّة لا مصدرَ لها» (و«١٦٥» في وثيقةٍ أخرى) **رقمان خاطئان**.
#   والسؤالُ الصحيح: «هل تعريفُها هو هو؟» — ومثالٌ مقيس: `send_booking_message`
#   في `supabase/schema/00-full-schema.sql` يثبّت `>= 3` بينما الحيّةُ تنادي
#   `taki_chat_limits()`. اسمٌ مطابقٌ وجسمٌ متخلّف.
#
# 🪤 ثلاثةُ عيوبٍ كشفها كسرُ النسخة الأولى من هذا الحارس، وكلُّها مُصلَحٌ هنا:
#   ① كان يَصرخ في كلِّ تشغيلةٍ لأن سطرَ وقت التوليد يتغيّر دائماً — إنذارٌ
#      دائمٌ يُدرّب على التجاهل. الآن السطورُ المتغيّرة موسومةٌ `@@VOLATILE`
#      وتُحذف من الطرفين قبل المقارنة.
#   ② لم يكن يُسمّي الدالّةَ المنحرفة: كان يبحث عن ترويسةٍ **متغيّرة** بدل
#      أقربِ ترويسةٍ **قبل** السطر المتغيّر. الآن يُسمّيها.
#   ③ وكان الفحصُ **يدهس لقطةَ المستودع** قبل أن يقارنها. الآن يصدّر إلى ملفٍّ
#      مؤقّت ولا يلمس المستودعَ إطلاقاً.
#
# 🪤 وهو ليس في `npm test`: يحتاج قاعدةَ الإنتاج، و`Vercel` تبني من أرشيفٍ بلا
#    شبكةٍ إلى جدة وبلا `.git` (دَرسٌ أسقط نشرتين). مكانُه يدُ مشغّلٍ أو كرون.
# ═══════════════════════════════════════════════════════════════════════════
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SNAP="$ROOT/supabase/schema/10-live-db-logic.sql"
NAMES_ONLY=0
[ "${1:-}" = "--names" ] && NAMES_ONLY=1

[ -f "$SNAP" ] || { echo "⛔ لا توجد لقطة. شغّل: bash scripts/export-db-logic.sh"; exit 2; }

LIVE="$(mktemp -t taki-live.XXXXXX)"
A="$(mktemp -t taki-a.XXXXXX)"
B="$(mktemp -t taki-b.XXXXXX)"
trap 'rm -f "$LIVE" "$A" "$B"' EXIT

# ① العقلُ الحيّ إلى ملفٍّ مؤقّت — ولا يُمَسُّ المستودع.
bash "$ROOT/scripts/export-db-logic.sh" --out "$LIVE" --quiet
rc=$?                                    # 🪤 تُقرأ مباشرةً: حالةُ الخروج عبر أنبوبٍ هي حالةُ الأنبوب
if [ "$rc" -ne 0 ]; then
  echo "⛔ تعذّر قراءةُ العقل الحيّ (حالة $rc) — ولا حكمَ بلا قياس."
  exit 2
fi

# ② تُحذف السطورُ المتغيّرة بطبيعتها من الطرفين، وإلّا صار الحارسُ ضجيجاً.
grep -v '@@VOLATILE' "$SNAP" > "$A"
grep -v '@@VOLATILE' "$LIVE" > "$B"

if cmp -s "$A" "$B"; then
  echo "✅ صفرُ انحراف — لقطةُ المستودع هي العقلُ الحيّ نفسُه."
  exit 0
fi

# ③ لكلِّ سطرٍ متغيّر: أقربُ ترويسةِ كائنٍ **قبله** هي المنحرف.
#    (نقرأ من النسخة الحيّة: هي المرجعُ، والمستودعُ هو المتخلّف.)
DRIFTED="$(
  diff --unified=0 "$A" "$B" 2>/dev/null \
  | awk '
      /^@@/ {
        # @@ -l,c +l,c @@  ← نأخذ سطرَ البداية في الطرف الجديد (+)
        for (i = 1; i <= NF; i++) if ($i ~ /^\+/) { split(substr($i, 2), p, ","); print p[1] }
      }' \
  | while read -r ln; do
      [ -n "$ln" ] || continue
      awk -v L="$ln" '
        NR <= L && /^-- ═══ (FUNCTION|TRIGGERS|RLS POLICIES|VIEWS|RLS STATE|GRANTS|CRON JOBS)/ { last = $0 }
        NR > L { print last; exit }
        END { if (last != "") print last }
      ' "$B"
    done \
  | sed -E 's/^-- ═══ FUNCTION /FUNCTION /; s/^-- ═══ /SECTION /; s/\(.*$//; s/ ═══$//' \
  | awk 'NF' | sort -u
)"
CHANGED="$(diff --unified=0 "$A" "$B" 2>/dev/null | grep -cE '^[-+][^-+]')"

if [ "$NAMES_ONLY" -eq 1 ]; then
  printf '%s\n' "$DRIFTED"
  exit 1
fi

echo "⚠️ انحرافٌ مرصود — العقلُ الحيّ لم يَعُد يطابق لقطةَ المستودع."
echo "   أسطرٌ متغيّرة: ${CHANGED:-؟}"
if [ -n "$DRIFTED" ]; then
  echo "   كائناتٌ منحرفة:"
  printf '%s\n' "$DRIFTED" | sed 's/^/     · /'
else
  echo "   (تعذّر ردُّ الفرق إلى كائنٍ بعينه — راجع الفرقَ كاملاً.)"
fi
echo
echo "   لتحديث اللقطة بعد هجرةٍ مقصودة:"
echo "     bash scripts/export-db-logic.sh && git add supabase/schema/10-live-db-logic.sql"
echo
echo "🪤 وانحرافٌ ليس خطأً بالضرورة: كلُّ هجرةٍ تُطبَّق على جدة تُنتجه حتى تُحدَّث"
echo "   اللقطة. الخطرُ انحرافٌ **لا يعرف أحدٌ سببَه**."
exit 1
