#!/usr/bin/env node
/**
 * build-logo.js — كلُّ مقاسات الشعار من أصلٍ واحد (v15.25)
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔴 ما كُشف عند القياس: شعارُ تاكي الحقيقيّ (الرجل على التكاية) **موجودٌ في
 *    المستودع بدقّة ٣٠٥٦×٤٠٩٦ شفّافاً ولا يُستعمل في أيّ مكان** — والموقعُ
 *    والتطبيقُ يعرضان مربّعاً أخضر بحرف T.
 *
 * 🪤 ولماذا سكربتٌ لا خطواتٌ يدويّة: المقاساتُ ستّة، وكلُّ تعديلٍ للشعار
 *    يتطلّب إعادتَها كلَّها. وخطوةٌ يدويّةٌ واحدةٌ منسيّة = أيقونةٌ قديمةٌ في
 *    موضعٍ واحد لا يلاحظه أحد. هنا أمرٌ واحد يُعيد بناءها جميعاً.
 *
 * 🪤 والرسمةُ تُقصّ إلى إطارها الحقيقي أوّلاً: الملفُّ الأصليّ فيه فراغٌ
 *    شفّافٌ واسع (الرسمةُ ٢٥٤٤×٢٤٢٠ داخل ٣٠٥٦×٤٠٩٦)، وبلا القصّ تخرج
 *    الأيقوناتُ صغيرةً في وسط فراغ.
 *
 * التشغيل:  node scripts/build-logo.js
 */
const { execFileSync } = require('child_process');
const path = require('path');
const root = path.resolve(__dirname, '..');

const out = execFileSync('python3', [path.join(__dirname, 'lib', 'logo_build.py')], {
    cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024,
});
process.stdout.write(out);
