// اختبار اشتقاق رابط واتساب (v14.77) — `shared/phone.js`.
// التشغيل:  node scripts/test-phone-links.js
//
// المعيار: زرُّ واتساب إمّا يفتح محادثةً صحيحة أو **لا يظهر**. الرابط المعطوب
// لا يُخطئ ولا يُسجَّل — واتساب يقول «الرقم غير صالح» فيُستنتج أن العميل ليس
// على واتساب، والخطأ في الرابط لا في العميل.
//
// 🪤 وكل متّجهٍ موجب هنا يقابله **متّجه سالب**: النمط القديم
// (`'966' + phone.replace(/^0/,'')`) يُحسب على نفس المدخل ويُثبَت أنه يُخرج
// شيئاً آخر. فحصٌ لا أستطيع وصف الكسر الذي يُفشله لا يُبنى.
const { waLink, waNumber, toLatinDigits } = require('../shared/phone.js');

let pass = 0, fail = 0;
const check = (name, got, want) => {
    const ok = got === want;
    console.log(`${ok ? '✅' : '❌'} ${name}`);
    if (!ok) console.log(`     توقّعنا ${JSON.stringify(want)} فجاء ${JSON.stringify(got)}`);
    ok ? pass++ : fail++;
};

const SA = 'https://wa.me/966512345678';

// ── الصيغ التي يكتبها الناس فعلاً ──────────────────────────────────────────
check('محلّي 05…',            waLink('0512345678'),        SA);
check('بمسافات وشرطات',        waLink('05 12-345 678'),     SA);
check('بمفتاح +966',           waLink('+966512345678'),     SA);
check('بمفتاح 00966',          waLink('00966512345678'),    SA);
check('966 بلا +',             waLink('966512345678'),      SA);
check('+966 ثم صفر (لصق شائع)', waLink('+9660512345678'),   SA);
check('بلا صفر ولا مفتاح',      waLink('512345678'),         SA);
check('أرقام عربية ٠٥…',       waLink('٠٥١٢٣٤٥٦٧٨'),        SA);
check('أرقام فارسية ۰۵…',      waLink('۰۵۱۲۳۴۵۶۷۸'),        SA);
check('بين قوسين وفواصل',      waLink('(966) 51-234-5678'), SA);

// ── ما يجب أن يُخفي الزرّ (فراغ) ────────────────────────────────────────────
check('فارغ',                  waLink(''),            '');
check('null',                  waLink(null),          '');
check('undefined',             waLink(undefined),     '');
check('نصّ بلا أرقام',          waLink('لا يوجد'),     '');
check('قصير جداً',              waLink('0512'),        '');
check('سعودي ناقص خانة',        waLink('051234567'),   '');
check('سعودي زائد خانة',        waLink('05123456789'), '');
check('سعودي لا يبدأ بـ5',      waLink('0412345678'),  '');
check('أصفار فقط',              waLink('0000'),        '');

// ── رقم دوليّ آخر يُمرَّر كما هو ─────────────────────────────────────────────
check('إماراتي +971',          waLink('+971501234567'), 'https://wa.me/971501234567');
check('مصري 0020',             waLink('00201001234567'), 'https://wa.me/201001234567');

// ── النفي: النمط القديم يُخرج شيئاً آخر على نفس المدخلات ────────────────────
// (لو لم يختلف المخرجان لكان هذا الإصلاح بلا أثر — فالنفي يُثبت أن له أثراً.)
const legacy = (p) => 'https://wa.me/966' + String(p || '').replace(/^0/, '');
const BROKEN = ['+966512345678', '00966512345678', '966512345678', '٠٥١٢٣٤٥٦٧٨', '05 12-345 678'];
for (const p of BROKEN) {
    const ok = legacy(p) !== waLink(p);
    console.log(`${ok ? '✅' : '❌'} النفي: «${p}» كان يخرج ${legacy(p)}`);
    ok ? pass++ : fail++;
}
// وعلى الصيغة الوحيدة التي كان يصيب فيها، لا نكون قد كسرنا شيئاً:
check('النمط القديم يصيب في 05… ونحن نوافقه', legacy('0512345678'), waLink('0512345678'));

// ── أداة الأرقام وحدها ──────────────────────────────────────────────────────
check('toLatinDigits عربية',   toLatinDigits('٠١٢٣٤٥٦٧٨٩'), '0123456789');
check('toLatinDigits تُبقي غيرها', toLatinDigits('أ٥ب'),      'أ5ب');
check('waNumber بلا بادئة',    waNumber('0512345678'),      '966512345678');

console.log(`\n${fail === 0 ? '✅' : '❌'} ${pass} نجح · ${fail} فشل`);
process.exit(fail === 0 ? 0 : 1);
