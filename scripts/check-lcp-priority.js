#!/usr/bin/env node
/**
 * check-lcp-priority.js — أوّلُ صفٍّ لا يُؤجَّل تحميلُه (v15.70)
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔴 كانت **كلُّ** صورةِ بطاقةٍ `loading="lazy"` بلا استثناء، ومنها أوّلُ
 *    بطاقةٍ يراها المستخدم. والمتصفّحُ لا يبدأ تحميلَ صورةٍ مؤجَّلةٍ حتى
 *    يكتمل التخطيط ⇒ تأخّر أكبرُ عنصرٍ يُرسم إلى **٤٦٧٦ م.ث** على جوّالٍ
 *    مخنوق، و**التقطه نصٌّ** لا صورة (قِيس عنصرُ LCP فعلاً).
 *
 * 🪤 والأرقامُ هنا **مقيسةٌ على جهازٍ حقيقيّ** لا مخمَّنة: على ٣٧٥×٨١٢ تبدأ
 *    شبكةُ العروض عند ٣٢٠، وأوّلُ بطاقتين عند ٣٢٨ ظاهرتان كاملتين (١٧١
 *    بكسلاً)، والصفُّ الذي بعدهما عند ٧٨٤ أي ٢٨ بكسلاً فقط. فاثنتان هو
 *    العددُ الصحيح — وتحميلٌ عاجلٌ لأكثرَ يُزاحم حزمةَ جافاسكربت على النطاق.
 *
 * 🪤 والرئيسيةُ **لا تُمسّ**: أكبرُ عنصرٍ فيها بانرٌ بـ٤٧٠٥٨ بكسل² عند ١٤٤
 *    وهو عاجلٌ أصلاً (ولذلك LCP فيها ٩٩٦ م.ث أخضر)، وبطاقاتُ رفّها عند ٧٥٥
 *    أي ٥٧ بكسلاً. فإضافةُ أولويّةٍ هناك كلفةٌ بلا مقابل.
 */

const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const fail = (m) => { console.error('❌ ' + m); process.exit(1); };
/**
 * 🔴 **تُجرَّد التعليقاتُ قبل أيّ فحصٍ نصّيّ — بلا استثناء.** أسقطَ هذا
 *    الحارسُ نفسَه على ملفٍّ سليم: شرحي «لا تستعمل `fetchPriority` بحرفٍ
 *    كبير» يحوي الكلمةَ التي يمنعها، فاتّهم الكودَ الصحيح. وهذه **خامسُ**
 *    مرّةٍ يقع هذا الفخُّ في المشروع — فصار التجريدُ شرطَ كلِّ قراءة، لا
 *    خطوةً تُذكر عند الحاجة.
 */
const strip = (t) => t.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
const read = (p) => strip(fs.readFileSync(path.join(ROOT, p), 'utf8'));

// ── ١) البطاقةُ تفرّق بين عاجلٍ ومؤجَّل ──────────────────────────────────
const card = read('src/components/DealCard.tsx');
if (!/loading=\{\s*priority\s*\?\s*'eager'\s*:\s*'lazy'\s*\}/.test(card)) {
    fail('DealCard لا تفرّق بين عاجلٍ ومؤجَّل — عادت كلُّ الصور إلى lazy،\n'
       + '   فيعود LCP يلتقط نصّاً متأخّراً بدل أوّل بطاقة.');
}
// 🪤 و`fetchpriority` **بحروفٍ صغيرة**: React 18.2 تُسقط `fetchPriority`
//    بتحذيرٍ ولا تُمرّرها إلى DOM، فالصيغةُ الكبيرة تمرّ هذا الفحصَ ولا تعمل.
if (!/fetchpriority:\s*'high'/.test(card)) {
    fail('DealCard بلا `fetchpriority: \'high\'` (بحروفٍ صغيرة) —\n'
       + '   React 18.2 تُسقط الصيغةَ الكبيرة `fetchPriority` بتحذير ولا تصل DOM.');
}
if (/fetchPriority/.test(card)) {
    fail('DealCard تستعمل `fetchPriority` بحرفٍ كبير — تُسقطها React 18.2 بصمتٍ عملياً.');
}

// ── ٢) وشبكةُ العروض تُمرّرها لأوّل صفٍّ وحده ────────────────────────────
const list = read('src/pages/DealsList.tsx');
if (!/priority=\{\s*i\s*<\s*2\s*\}/.test(list)) {
    fail('DealsList لا تُمرّر `priority={i < 2}` — أوّلُ صفٍّ يعود مؤجَّلاً.\n'
       + '   (والعددُ ٢ مقيسٌ: عمودان ظاهران كاملين، والصفُّ بعدهما ٢٨ بكسلاً.)');
}
// 🪤 ولا تُعطى لكلّ البطاقات: تحميلٌ عاجلٌ للشبكة كلّها يُزاحم الحزمة.
if (/priority=\{\s*true\s*\}|priority\s*(?![:?])/.test(list.replace(/priority=\{\s*i\s*<\s*2\s*\}/g, ''))) {
    fail('DealsList تُعطي الأولويّةَ لأكثرَ من أوّل صفّ — تحميلٌ عاجلٌ للشبكة\n'
       + '   كلّها يُزاحم حزمةَ جافاسكربت على النطاق فيُبطئ كلَّ شيء.');
}

// ── ٣) والعقدُ يُثبَت في **المُخرَج** لا في المصدر ───────────────────────
// 🪤 فمصدرٌ سليمٌ لا يُثبت حزمةً سليمة: React قد تُسقط خاصّيّةً لا تعرفها،
//    والدليلُ الوحيد ظهورُها في الكود المولَّد.
const DIST = path.join(ROOT, 'dist');
if (fs.existsSync(DIST)) {
    const hit = fs.readdirSync(DIST).filter((f) => f.endsWith('.js'))
        .some((f) => fs.readFileSync(path.join(DIST, f), 'utf8').includes('fetchpriority'));
    if (!hit) {
        fail('`fetchpriority` غائبةٌ عن كلّ حزم dist — لم تصل إلى المُخرَج،\n'
           + '   فالمصدرُ يقولها والمتصفّحُ لا يراها.');
    }
}
console.log('✅ أولويّةُ أوّل صفّ: البطاقةُ تفرّق · الشبكةُ تُمرّر لاثنتين · ووصلت إلى المُخرَج');

// ═══════════════════════════════════════════════════════════════════════════
// ٥) الهيرو من ملفٍّ ثابتٍ لا من محوِّلٍ آنيّ
// ───────────────────────────────────────────────────────────────────────────
// 🔴 قِيس أن محوّلَ الصور على الخادم **لا يخزّن شيئاً** (بارد ≈ متكرّر) ويكلّف
//    `x-kong-upstream-latency: 412` م.ث لكلّ طلب — أي سقفُ ~٢٫٤ مشاهدةٍ في
//    الثانية على نواةٍ واحدة. والملفُّ الثابتُ `_h.jpg` قِيس بـ**٦ م.ث**.
//    فالعودةُ إلى المحوّل في الهيرو تُعيد سقفاً يُسقط الموقعَ تحت أيّ موجة.
{
    const thumb = read('src/utils/thumb.ts');
    if (!/export const heroUrl/.test(thumb)) {
        fail('`heroUrl` غائبةٌ عن utils/thumb.ts — عاد الهيرو إلى المحوّل الآنيّ.');
    }
    if (!/_h\.jpg/.test(thumb)) {
        fail('`heroUrl` لا تشير إلى التوأم الثابت `_h.jpg`.');
    }
    const dd = read('src/pages/DealDetails.tsx');
    if (!/src=\{heroUrl\(/.test(dd)) {
        fail('الهيرو في DealDetails لا يستعمل `heroUrl` —\n'
           + '   فإمّا عاد إلى الأصل الكامل (٢٨٠١ ك.ب) أو إلى محوّلٍ بـ٤١٢ م.ث لكلّ مشاهدة.');
    }
    // 🪤 ولا يُصيَّر الأصلُ خاماً في الهيرو: `images[currentImage]` عارياً
    //    في `src` هو العيبُ الذي جاء هذا كلُّه لأجله.
    if (/src=\{images\[currentImage\]\}/.test(dd)) {
        fail('الهيرو يُصيّر `images[currentImage]` خاماً — ٢٨٠١ ك.ب لشاشةِ ٣٩٠ بكسلاً.');
    }
    const store = read('src/services/storageService.ts');
    if (!/_h\.jpg/.test(store) || !/HERO/.test(store)) {
        fail('الرفعُ لا يُنتج توأمَ الهيرو `_h.jpg` — فكلُّ صورةٍ جديدة تعود\n'
           + '   إلى المحوّل الآنيّ، ويعود السقفُ تدريجياً.');
    }
    console.log('✅ الهيرو: توأمٌ ثابتٌ عند الرفع · و`heroUrl` تُفضّله · ولا أصلَ خاماً');
}
