#!/usr/bin/env node
/**
 * check-alert-tone.js — النغمةُ تُسمع، وتتكرّر، وتتوقّف (v16.57)
 *
 * ── العيوبُ التي يحرسها ─────────────────────────────────────────────────
 * ① 🔴 **`new Audio()` لكلّ نغمة ⇒ صوتٌ لا يُسمع.** المتصفّحُ يمنح إذنَ
 *    التشغيل التلقائي **للعنصر الذي لمسه المستخدم**، وعنصرٌ يُولد لحظةَ
 *    الحدث لا يرثه — فتُرفض `play()` بصمت. وهذا سببُ بلاغ ناصر: الصوتُ
 *    مكتوبٌ في الكود منذ v16.02 ولا يُسمع.
 * ② 🔴 **تكرارٌ لا يتوقّف.** ربطُ الإيقاف بحدثِ «استلام» يترك الطلبَ يدقّ إن
 *    وصل التغييرُ بمسارٍ آخر (إعادةُ جلب · إلغاءٌ من المشتري · انتهاءُ مهلة).
 *    والمقارنةُ بالقائمة (`syncRepeating`) هي ما يُصيب كلَّ المسارات.
 * ③ 🔴 **نغمةٌ على ما كتبتَه أنت.** صوتٌ يرتدّ عند إرسالك رسالةً إزعاجٌ بلا
 *    معنى — فالشرطُ على **الوارد** وحده.
 * ④ **وتكرارٌ للمشتري.** هو يعرف أنه حجز للتوّ؛ التكرارُ للتاجر وحده.
 *
 * 🪤 ويُجرَّد التعليقُ قبل أيّ فحص.
 */
const fs = require('fs');
const path = require('path');

const R = (p) => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
/**
 * 🪤 ويُزال **التعليقُ اللاحقُ للكود** أيضاً، لا المستقلُّ وحده: أوّلُ تشغيلٍ
 *    لهذا الحارس سقط على تعليقٍ في `AppContext` يقول «لا `new Audio()` يُحجب»
 *    — فأمسك نفسَه (الفخُّ رقم عشرة من نوعه في هذا المشروع).
 * 🪤 و`(?<!:)` تحمي `https://` من أن يُقطع نصفُ السطر عنده.
 */
const strip = (src) => src
    .replace(/(^[ \t]*|\{)\/\*[\s\S]*?\*\//gm, '$1')
    .replace(/^[ \t]*\/\/[^\n]*$/gm, '')
    .replace(/(?<!:)\/\/[^\n]*$/gm, '')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '');

let pass = 0, fail = 0;
const check = (name, ok, detail) => {
    console.log(`${ok ? '  ✓' : '  ✗'} ${name}`);
    if (!ok && detail) console.log(`      ${detail}`);
    ok ? pass++ : fail++;
};

const SND  = strip(R('src/services/notificationSound.ts'));
const HOOK = strip(R('src/hooks/useOrderAlertTone.ts'));
const CTX  = strip(R('src/context/AppContext.tsx'));

console.log('\nنغمةُ التنبيه — تُسمع · تتكرّر · وتتوقّف');

// ── ① تُسمع ─────────────────────────────────────────────────────────────
check('عنصرُ الصوت **واحدٌ يُعاد استعماله**',
    /let el: HTMLAudioElement \| null = null/.test(SND) && /if \(!el\)/.test(SND),
    'عنصرٌ لكلّ نغمة لا يرث إذنَ التشغيل التلقائي فيُحجب بصمت');
check('ويُفتح قفلُه عند أوّل تفاعلٍ حقيقيّ',
    /addEventListener\(ev, open, \{ once: true/.test(SND)
    && /'pointerdown', 'touchstart', 'keydown'/.test(SND),
    'بلا فتحٍ عند لمسةٍ من المستخدم تبقى كلُّ نغمةٍ محجوبة');
check('والفتحُ يُنادى فعلاً من خطّافٍ يعمل في كلّ جلسة',
    /unlockSound\(\)/.test(HOOK),
    'دالّةٌ تُعرَّف ولا تُنادى = نفسُ العيب بلا صوت');
check('ولا `new Audio` في السياق بعد اليوم',
    !/new Audio\(/.test(CTX),
    'عاد إنشاءُ عنصرٍ لكلّ نغمة');

// ── ② تتكرّر وتتوقّف ────────────────────────────────────────────────────
check('التكرارُ يُوفَّق بالقائمة لا بحدثٍ بعينه',
    /export const syncRepeating/.test(SND) && /syncRepeating\(waiting\)/.test(HOOK),
    'ربطُ الإيقاف بحدثٍ واحدٍ يترك الطلبَ يدقّ إن وصل التغييرُ بمسارٍ آخر');
check('ومفتاحٌ قائمٌ لا يُنشئ مؤقّتاً ثانياً',
    /if \(!key \|\| timers\.has\(key\)\) return;/.test(SND),
    'طلبان معلّقان ينتجان نغمتين متداخلتين');
check('وسقفٌ للتكرار شبكةَ أمان',
    /MAX_REPEATS/.test(SND) && /t\.left <= 0/.test(SND),
    'تطبيقٌ يبقى مفتوحاً طوالَ الليل يدقّ حتى الصباح');
check('🔴 ولا يُسكتها كونُ الصفحةِ مخفيّة',
    !/document\.hidden\)\s*return;/.test(SND),
    'قِيس بكروم: بعد اللمسة تنجح `play()` وهي مخفيّة و`currentTime` يتقدّم. '
    + 'ومنعُها هناك يُسكت النغمةَ حين يكون التاجرُ في تابٍ آخر — وهو عكسُ المطلوب');
check('وكلُّ تكرارٍ يُوقَف عند الخروج',
    /stopAllRepeating/.test(HOOK) && /useEffect\(\(\) => \(\) => \{ stopAllRepeating\(\); \}, \[\]\)/.test(HOOK),
    'تبديلُ الحساب يترك نغمةَ تاجرٍ سابقٍ تدقّ');

// ── ③④ من يسمعها ───────────────────────────────────────────────────────
check('نغمةُ الرسالة **للوارد وحده**',
    /row\.sender_id !== user\?\.id\) playSoundOnce\(\)/.test(CTX),
    'نغمةٌ على ما كتبتَه أنت ارتدادٌ مزعج');
check('والتكرارُ **للتاجر وحده** وعلى `pending` فقط',
    /b\?\.status === 'pending' && b\?\.deal\?\.storeId === userId/.test(HOOK),
    'المشتري يعرف أنه حجز للتوّ · و`acknowledged` تعني أن التاجر انتبه');

console.log(`\n${fail === 0 ? '✅' : '❌'} ${pass} ناجح · ${fail} فاشل\n`);
process.exit(fail === 0 ? 0 : 1);
