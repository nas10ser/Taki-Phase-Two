#!/usr/bin/env node
/**
 * check-refund-guard.js — نقرتان لا تُخرجان المبلغ مرّتين (v15.01)
 * ═══════════════════════════════════════════════════════════════════════════
 * 🔴 طلبُ ناصر حرفياً: «واريد الاسترداد مره وحده فلا ينقر مرتين ورا بعض فيذهب
 *    المبلغ مرتين». وهو محقّ في القلق: **الاسترداد ليس عمليةً آمنة التكرار**
 *    عند أربعٍ من ستّ بوّابات (ميسر · تاب · باي‑تابس · هايبر‑باي لا تملك
 *    مفتاح تكرارٍ إطلاقاً) — نداءان = خصمان من حساب التاجر.
 *
 * والدفاع ثلاث طبقات، وهذا الحارس يحرس الطبقة الأولى والثانية:
 *   ١. `ref` يُكتب **فوراً** عند النقر، قبل أي حوار.  ← هنا
 *   ٢. والزرّ يُعطَّل بالحالة (`disabled={busy}`).      ← هنا
 *   ٣. وقفلُ الصفّ في القاعدة (`FOR UPDATE` ثم `ALREADY_CLAIMING`) هو الحَكَم
 *      النهائي — مُثبَتٌ داخل هجرة v14.97 بنداءين متزامنين على صفٍّ حقيقي.
 *
 * 🪤 ولماذا `ref` لا `useState` وحدها: `setState` غيرُ متزامن. نقرتان في نفس
 *    إطار الرسم تقرآن القيمة القديمة `false` كلتاهما فتمرّان. والعيب الذي كان
 *    قائماً فعلاً قبل v15.01: `setBusy(true)` كان **بعد** حوارَي السؤال
 *    والتأكيد — أي أن الزرّ يبقى حيّاً ثوانيَ يقرأ فيها التاجر النصّ.
 *
 * 🪤 ولا يفترض هذا الحارس git ولا `dist` — يعمل داخل بناء Vercel أيضاً.
 */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const fail = (m) => { console.error(`\n❌ البناء متوقّف: حارس الاسترداد\n\n   ${m}\n`); process.exit(1); };

const FILE = path.join(root, 'src', 'components', 'seller', 'RefundButton.tsx');
let src;
try { src = fs.readFileSync(FILE, 'utf8'); } catch { fail('src/components/seller/RefundButton.tsx غير موجود.'); }

// ── ١) حارسٌ متزامن موجود ─────────────────────────────────────────────────
if (!/useRef\s*\(/.test(src) || !/inFlight/.test(src)) {
    fail('لا حارسَ متزامناً (`useRef`) في زرّ الاسترداد — `useState` وحدها تمرّ نقرتين في إطارٍ واحد.');
}
if (!/if\s*\(\s*inFlight\.current\s*\)\s*return\s*;/.test(src)) {
    fail('الحارس لا يعود مبكّراً: يلزم `if (inFlight.current) return;` كأوّل سطرٍ في المعالج.');
}
if (!/inFlight\.current\s*=\s*true/.test(src) || !/inFlight\.current\s*=\s*false/.test(src)) {
    fail('الحارس يُرفع ولا يُخفض (أو العكس) — الزرّ سيبقى مقفلاً للأبد أو لن يُقفل.');
}
// ويُخفَض في `finally` وإلا بقي مقفلاً عند أي استثناء
if (!/finally\s*\{[\s\S]{0,200}inFlight\.current\s*=\s*false/.test(src)) {
    fail('`inFlight` لا يُخفَض داخل `finally` — استثناءٌ واحد يُقفل الزرّ إلى الأبد.');
}

// ── ٢) القفل **قبل** أي حوار — وهذا هو العيب الذي كان قائماً ──────────────
const handler = src.slice(src.indexOf('const doRefund'));
const iGuard = handler.indexOf('inFlight.current = true');
const iPrompt = handler.search(/customPrompt|customConfirm/);
if (iGuard < 0) fail('لم أجد رفعَ الحارس في المعالج.');
if (iPrompt >= 0 && iPrompt < iGuard) {
    fail('الحوار يسبق القفل — الزرّ يبقى حيّاً طوال قراءة التاجر للنصّ، وهذا بالضبط العيب الذي أُصلح في v15.01.');
}

// ── ٣) والزرّ معطَّلٌ بصرياً أيضاً ─────────────────────────────────────────
if (!/disabled=\{busy\}/.test(src)) {
    fail('الزرّ لا يُعطَّل بـ`disabled={busy}` — المستخدم يرى زرّاً حيّاً أثناء التنفيذ.');
}

// ── ٤) ولا يُقال «نجح» بلا دليلٍ من الردّ ─────────────────────────────────
if (!/res\.ok/.test(src)) {
    fail('نتيجةُ النداء لا تُفحص — «تمّ الردّ» بلا دليلٍ أخطرُ من خطأ.');
}

// ── ٥) والنتيجةُ المجهولة لا تُعرض كفشل ──────────────────────────────────
// (٥٠٢ تعني «ربّما خرج المال» — عرضُها كفشلٍ يدفع التاجر لإعادة المحاولة.)
if (!/502|REFUND_OUTCOME_UNKNOWN|غير معلوم|مجهول/.test(src)) {
    fail('لا معالجةَ للنتيجة المجهولة (٥٠٢) — رسالةُ فشلٍ عامّة هناك تدفع التاجر لردٍّ ثانٍ.');
}

// ── ٦) والقاعدةُ ما زالت الحَكَم: الهجرة تحمل القفل ───────────────────────
const MIG = path.join(root, 'supabase', 'JEDDAH_v14_97_instant_refund.sql');
let sql;
try { sql = fs.readFileSync(MIG, 'utf8'); } catch { fail('هجرة v14.97 غير موجودة — القفل النهائي فيها.'); }
for (const [needle, why] of [
    ['FOR UPDATE', 'قفلُ الصفّ غائبٌ عن دالّة الطلب — نداءان متزامنان يمرّان معاً.'],
    ['ALREADY_CLAIMING', 'لا رمزَ للنداء الثاني — سيبدو نجاحاً.'],
]) {
    if (!sql.includes(needle)) fail(why);
}

console.log('✅ حارس الاسترداد: قفلٌ متزامن قبل أي حوار · زرٌّ معطَّل · نتيجةٌ تُفحص · والقاعدة تقفل الصفّ');
